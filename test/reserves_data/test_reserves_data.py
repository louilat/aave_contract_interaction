def test_transform_configuration_data(reserves_data):
    configuration_data = transform_reserves_configuration_data(2014.0718, reserves_data)

    assert len(configuration_data) == 10
    assert configuration_data.columns.tolist() == [
        "underlyingAsset",
        "name",
        "symbol",
        "decimals",
        "baseLTVasCollateral",
        "reserveLiquidationThreshold",
        "reserveLiquidationBonus",
        "reserveFactor",
        "usageAsCollateralEnabled",
        "borrowingEnabled",
        "isActive",
        "isFrozen",
        "query_timestamp"
    ]

    assert np.min(configuration_data.query_timestamp) == np.max(configuration_data.query_timestamp) == 2014.0718


